import { build } from 'esbuild';
import { copyFile, mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const result = await build({
  absWorkingDir: root,
  entryPoints: ['game/main.ts'],
  bundle: true,
  write: false,
  format: 'iife',
  target: ['es2020'],
  minify: true,
  legalComments: 'eof',
  loader: { '.png': 'dataurl', '.jpg': 'dataurl', '.jpeg': 'dataurl', '.webp': 'dataurl', '.svg': 'dataurl', '.glb': 'dataurl', '.gltf': 'text', '.mp3': 'dataurl', '.ogg': 'dataurl', '.wav': 'dataurl' },
  define: { 'process.env.NODE_ENV': '"production"' },
});
const css = await readFile(resolve(root, 'game/style.css'), 'utf8');
const js = result.outputFiles.find(file => file.path.endsWith('.js'))?.text || result.outputFiles[0].text;
const html = `<!doctype html>
<html lang="tr"><head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1,maximum-scale=1,user-scalable=no,viewport-fit=cover">
<meta name="theme-color" content="#071419">
<meta name="description" content="DraBornLand: keşfet, hayatta kal, barınağını kur ve kayıp adanın sırrını çöz. Ücretsiz üçüncü şahıs ada survival oyunu.">
<title>DraBornLand · Kayıp Adanın Çağrısı</title>
<link rel="icon" href="data:image/svg+xml,%3Csvg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 64 64'%3E%3Crect width='64' height='64' rx='14' fill='%23071419'/%3E%3Cpath d='M12 46 26 17 38 35 45 23 55 46Z' fill='%23e5b96b'/%3E%3C/svg%3E">
<style>${css.replace(/<\/style/gi, '<\\/style')}</style>
<script>window.addEventListener('error',function(e){if(window.ReactNativeWebView)window.ReactNativeWebView.postMessage(JSON.stringify({type:'error',message:e.message}));});</script>
</head><body><div id="app"></div><script>${js.replace(/<\/script/gi, '<\\/script')}</script></body></html>`;
await mkdir(resolve(root, 'web'), { recursive: true });
await mkdir(resolve(root, 'generated'), { recursive: true });
await writeFile(resolve(root, 'web/index.html'), html);
await writeFile(resolve(root, 'generated/game-html.ts'), `// Generated by npm run build. Source: game/main.ts and game/style.css.\nexport const GAME_HTML = ${JSON.stringify(html)};\n`);
// Optional share-card files do not participate in the offline game runtime.
try {
  const entries = await readdir(resolve(root, 'assets'));
  for (const name of entries.filter(name => /^(social|og|cover)\./.test(name))) {
    await copyFile(resolve(root, 'assets', name), resolve(root, 'web', name));
  }
} catch (error) { if (error.code !== 'ENOENT') throw error; }
console.log(`DraBornLand web + Expo offline HTML hazır (${(Buffer.byteLength(html) / 1024).toFixed(0)} KB).`);
